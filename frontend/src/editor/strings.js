export const EDITOR_STRINGS = { en, de };

/** Look up a string and fill {placeholders}. Falls back to English, then to the key. */
export function translate(lang, key, vars) {
  const base = String(lang || "en").toLowerCase().split(/[-_]/)[0];
  const table = EDITOR_STRINGS[base] || en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Format a number with the language's decimal separator. */
export function formatNumber(lang, v, digits = 2) {
  const base = String(lang || "en").toLowerCase().split(/[-_]/)[0];
  if (v == null || !Number.isFinite(v)) return "";
  return new Intl.NumberFormat(base === "de" ? "de-DE" : "en-GB", {
    minimumFractionDigits: 0,
    maximumFractionDigits: digits,
    useGrouping: false,
  }).format(v);
}

/** Parse a user-typed number; accepts a decimal comma. Empty → null, invalid → NaN. */
export function parseNumber(text) {
  const s = String(text ?? "").trim().replace(",", ".");
  if (s === "") return null;
  const v = Number(s);
  return Number.isFinite(v) ? v : NaN;
}
